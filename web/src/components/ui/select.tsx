function SelectTrigger({
  className,
  size = "default",
  children,
  ...props
}: SelectPrimitive.Trigger.Props & {
  size?: "sm" | "default"
}) {
  return (
    <SelectPrimitive.Trigger
      data-slot="select-trigger"
      data-size={size}
      className={cn(
        "group/select flex w-fit items-center justify-between gap-2 rounded-md border border-input/70 bg-card py-2 pr-3 pl-3.5 text-sm whitespace-nowrap text-foreground transition-[border-color,box-shadow] duration-150 ease-standard outline-none select-none hover:border-foreground/70 focus-visible:border-primary focus-visible:shadow-[inset_0_0_0_1px_var(--primary)] focus-visible:outline-none disabled:cursor-not-allowed disabled:border-disabled disabled:text-disabled-foreground aria-invalid:border-destructive data-placeholder:text-muted-foreground data-popup-open:border-primary data-popup-open:shadow-[inset_0_0_0_1px_var(--primary)] data-[size=default]:h-11 data-[size=sm]:h-9 data-[size=sm]:rounded-full data-[size=sm]:pl-4 *:data-[slot=select-value]:line-clamp-1 *:data-[slot=select-value]:flex *:data-[slot=select-value]:items-center *:data-[slot=select-value]:gap-1.5 dark:bg-transparent data-disabled:cursor-not-allowed data-disabled:text-disabled-foreground [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-[18px]",
        className
      )}
      {...props}
    >
      {children}
      <SelectPrimitive.Icon
        render={
          <ChevronDownIcon className="pointer-events-none size-[18px] text-muted-foreground transition-transform duration-150 group-data-popup-open/select:rotate-180" />
        }
      />
    </SelectPrimitive.Trigger>
  )
}

function SelectContent({
  className,
  children,
  side = "bottom",
  sideOffset = 4,
  align = "center",
  alignOffset = 0,
  alignItemWithTrigger = false,
  ...props
}: SelectPrimitive.Popup.Props &
  Pick<
    SelectPrimitive.Positioner.Props,
    "align" | "alignOffset" | "side" | "sideOffset" | "alignItemWithTrigger"
  >) {
  return (
    <SelectPrimitive.Portal>
      <SelectPrimitive.Positioner
        side={side}
        sideOffset={sideOffset}
        align={align}
        alignOffset={alignOffset}
        alignItemWithTrigger={alignItemWithTrigger}
        className="isolate z-50"
      >
        <SelectPrimitive.Popup
          data-slot="select-content"
          data-align-trigger={alignItemWithTrigger}
          className={cn(
            "relative isolate z-50 max-h-(--available-height) w-(--anchor-width) min-w-40 origin-(--transform-origin) overflow-x-hidden overflow-y-auto rounded-md bg-popover py-2 text-popover-foreground shadow-e2 transition-[opacity,transform] duration-150 ease-standard data-ending-style:opacity-0 data-starting-style:scale-[0.98] data-starting-style:opacity-0 data-[align-trigger=true]:transition-none dark:border dark:border-border",
            className
          )}
          {...props}
        >
          <SelectScrollUpButton />
          <SelectPrimitive.List>{children}</SelectPrimitive.List>
          <SelectScrollDownButton />
        </SelectPrimitive.Popup>
      </SelectPrimitive.Positioner>
    </SelectPrimitive.Portal>
  )
}

